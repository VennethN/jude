export type Key = keyof typeof messages;
export function translate(lang:Lang, key:Key, values?:Record<string,number|string>) {
	let text:string = messages[key][lang === 'id' ? 0 : 1];
	if (text.includes('|')) text=text.split('|')[values?.n === 1 ? 0 : 1];
	return values ? text.replace(/\{(\w+)\}/g,(_,name:string)=>String(values[name] ?? '')) : text;
}
